# Python Day 5: Advanced String Slicing
text = "PYTHONPROGRAMMING"
# Slicing from the last 5 characters
print(text[-5:])
# Print every third character
print(text[::3])
# From index 2 to the end
print(text[2:])
# From the beginning up to (but not including) index 5
print(text[:5])
# Reverse the entire string
print(text[::-1])
# Print every second character
print(text[::2])
# Print every third character
print(text[::3])
# Indexing returns a single character,
# while slicing returns one or more characters (a substring).